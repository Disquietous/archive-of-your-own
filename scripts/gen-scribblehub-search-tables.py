#!/usr/bin/env python3
"""Regenerate core/src/source/scribblehub/search_tables.rs from a saved copy
of ScribbleHub's Series Finder page (site vocabulary: genres, content
warnings, tags, contests — no user data).

    python3 -I scripts/gen-scribblehub-search-tables.py design/scribblehub/series-search.txt

Bump `VERSION` in core/src/source/scribblehub/search.rs after a regeneration
that changes the tables.
"""
import html
import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "core/src/source/scribblehub/search_tables.rs"


def rust_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def table(name: str, doc: str, pairs: list[tuple[str, str]]) -> str:
    rows = "\n".join(f"    ({rust_str(v)}, {rust_str(l)})," for v, l in pairs)
    return f"/// {doc}\npub const {name}: &[(&str, &str)] = &[\n{rows}\n];\n"


def main(path: str) -> None:
    src = Path(path).read_text(encoding="utf-8", errors="replace")
    f0 = src.find('<form id="rankfilter"')
    f1 = src.find("</form>", f0)
    if f0 < 0 or f1 < 0:
        sys.exit("finder form (form#rankfilter) not found")
    form = src[f0:f1]

    genres = [(a, html.unescape(b).strip()) for a, b in
              re.findall(r'gmeid="(\d+)"[^>]*>.*?<span class="lbl_cl sfgenre"[^>]*>([^<]*)<', form, re.S)]
    warnings = [(a, html.unescape(b).strip()) for a, b in
                re.findall(r'ctid="(\d+)"[^>]*>.*?<span class="lbl_cl sfmature"[^>]*>([^<]*)<', form, re.S)]

    def select_options(name: str) -> list[tuple[str, str]]:
        m = re.search(r'<select[^>]*name="' + re.escape(name) + r'"[^>]*>(.*?)</select>', form, re.S)
        if not m:
            sys.exit(f"select {name} not found")
        return [(v, html.unescape(l).strip()) for v, l in
                re.findall(r'<option[^>]*value="([^"]*)"[^>]*>([^<]*)', m.group(1))]

    tags = select_options("tagsalledit_include[]")
    contests = [(v, l) for v, l in select_options("contestselect") if v != "0"]

    for name, rows in (("genres", genres), ("warnings", warnings), ("tags", tags), ("contests", contests)):
        if not rows:
            sys.exit(f"no {name} found")
        values = [v for v, _ in rows]
        if len(set(values)) != len(values):
            sys.exit(f"duplicate {name} ids")

    out = (
        "//! ScribbleHub Series Finder vocabulary. GENERATED by\n"
        "//! `scripts/gen-scribblehub-search-tables.py` from a saved copy of the\n"
        "//! finder page — do not edit by hand.\n\n"
        + table("GENRES", "Genre id (`gmeid`) and name, in the finder's order.", genres) + "\n"
        + table("CONTENT_WARNINGS", "Content warning id (`ctid`) and name.", warnings) + "\n"
        + table("TAGS", "Tag id and name (`tagsalledit_include[]` options).", tags) + "\n"
        + table("CONTESTS", "Contest id (`contestselect`) and name.", contests)
    )
    OUT.write_text(out, encoding="utf-8")
    print(f"wrote {OUT}: {len(genres)} genres, {len(warnings)} warnings, {len(tags)} tags, {len(contests)} contests")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
