#!/usr/bin/env python3
"""Regenerate core/src/source/ao3/languages.rs from the archive's works
search form as the app last scraped it (the `searchFormFields` session
cache, dumped by build/db-query/queries/search_form.sql), or from a saved
copy of the form's HTML.

    python3 -I scripts/gen-ao3-languages.py build/db-query/out/search_form.txt
    python3 -I scripts/gen-ao3-languages.py saved-search-form.html

Site vocabulary only (language ids and names). Bump `VERSION` in
core/src/source/ao3/search.rs after a regeneration that changes the list.
"""
import html
import json
import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "core/src/source/ao3/languages.rs"


def from_cache_dump(text: str) -> list[tuple[str, str]]:
    """The db-query box table holds one JSON cell: the scraped field list."""
    start, end = text.find("["), text.rfind("]")
    if start < 0 or end < 0:
        sys.exit("no JSON array in the dump")
    fields = json.loads(text[start:end + 1])
    for f in fields:
        if "[language_id]" in f.get("name", ""):
            return [(o["value"], o["label"].strip()) for o in f.get("options", []) if o.get("value")]
    sys.exit("no language field in the dump")


def from_html(text: str) -> list[tuple[str, str]]:
    m = re.search(r'<select[^>]*name="work_search\[language_id\]"[^>]*>(.*?)</select>', text, re.S)
    if not m:
        sys.exit("no language select in the HTML")
    return [(v, html.unescape(l).strip()) for v, l in
            re.findall(r'<option[^>]*value="([^"]*)"[^>]*>([^<]*)', m.group(1)) if v]


def main(path: str) -> None:
    text = Path(path).read_text(encoding="utf-8", errors="replace")
    langs = from_html(text) if "<select" in text else from_cache_dump(text)
    if not langs:
        sys.exit("empty language list")
    ids = [v for v, _ in langs]
    if len(set(ids)) != len(ids):
        sys.exit("duplicate language ids")
    rows = "\n".join(f'    ({json.dumps(v)}, {json.dumps(l, ensure_ascii=False)}),' for v, l in langs)
    OUT.write_text(
        "//! AO3 language ids and names, in the archive's order. GENERATED by\n"
        "//! `scripts/gen-ao3-languages.py` from the archive's works search form —\n"
        "//! do not edit by hand.\n\n"
        f"pub const LANGUAGES: &[(&str, &str)] = &[\n{rows}\n];\n",
        encoding="utf-8")
    print(f"wrote {OUT}: {len(langs)} languages")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
